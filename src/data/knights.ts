/**
 * 按组获取骑士（按编号前缀分组）
 */
export function getKnightGroups(): Record<string, KnightArchetype[]> {
  const groups: Record<string, KnightArchetype[]> = {};
  KNIGHT_DB.forEach(k => {
    const prefix = k.number.split('-')[0];
    if (!groups[prefix]) groups[prefix] = [];
    groups[prefix].push(k);
  });
  return groups;
}

/**
 * 根据 ID 获取骑士
 */
export function getKnightById(id: string): KnightArchetype | undefined {
  return KNIGHT_DB.find(k => k.id === id);
}

/**
 * 获取骑士显示名称
 */
export function getKnightLabel(knightId: string): string {
  if (knightId === 'custom') return '自定义骑士 (Custom Knight)';
  const knight = getKnightById(knightId);
  return knight ? `${knight.number}: ${knight.name}` : knightId;
}
