/**
 * 按组获取神话（按编号前缀分组）
 */
export function getMythGroups(): Record<string, MythArchetype[]> {
  const groups: Record<string, MythArchetype[]> = {};
  MYTH_DB.forEach(m => {
    const prefix = m.number.split('-')[0];
    if (!groups[prefix]) groups[prefix] = [];
    groups[prefix].push(m);
  });
  return groups;
}

/**
 * 根据 ID 获取神话
 */
export function getMythById(id: string): MythArchetype | undefined {
  return MYTH_DB.find(m => m.id === id || m.number === id);
}

/**
 * 获取神话显示名称
 */
export function getMythLabel(mythId: string): string {
  const myth = getMythById(mythId);
  return myth ? `${myth.number}: ${myth.name}` : mythId;
}
